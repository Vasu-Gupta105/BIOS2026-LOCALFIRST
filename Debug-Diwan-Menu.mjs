import { chromium, expect } from './diwan/web/node_modules/@playwright/test/index.mjs'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage()
page.on('pageerror', e => console.log('browser error:', e.message))
await page.goto('http://127.0.0.1:47519/docs')
await page.getByRole('button', { name: 'New Document', exact: true }).first().click()
await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Menu debugging')
await page.getByRole('button', { name: 'Create', exact: true }).click()
await expect(page.getByRole('textbox', { name: 'Document content' })).toHaveAttribute('contenteditable', 'true')
await page.getByRole('button', { name: 'Back to Docs', exact: true }).click()
await page.evaluate(() => { window.menuClicks = []; for (const type of ['pointerdown', 'pointerup', 'click']) document.addEventListener(type, e => window.menuClicks.push({ type, target: e.target.outerHTML.slice(0, 400), x: e.clientX, y: e.clientY }), true) })
await page.getByRole('button', { name: 'File actions', exact: true }).click()
console.log('trash bounds', await page.getByRole('button', { name: 'Move to trash', exact: true }).boundingBox())
await page.getByRole('button', { name: 'Move to trash', exact: true }).click()
await page.waitForTimeout(200)
console.log('clicked', await page.evaluate(() => window.menuClicks))
console.log('buttons', await page.getByRole('button').allTextContents())
console.log('records', await page.evaluate(() => new Promise(resolve => { const r = indexedDB.open('diwan-local-workspace'); r.onsuccess = () => { const db = r.result; const tx = db.transaction('files'); tx.objectStore('files').getAll().onsuccess = e => resolve(e.target.result); tx.oncomplete = () => db.close() } })))
await page.screenshot({ path: 'Diwan-menu-debug.png', fullPage: true })
await browser.close()
